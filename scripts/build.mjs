// Builds dist/ from src/: inlines the SVG artwork into the page, generates the program artwork
// module and adds content hashes to CSS/JS URLs so browsers never keep a stale version.
// --with-server points the consultation form at /api/leads (server/index.mjs); without it the
// site is fully static (Vercel) and the form prepares a Telegram draft.
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const graphicsDir = path.join(srcDir, 'assets/graphics');
const programKeys = ['children', 'adults', 'exams', 'business'];

const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 10);

async function readArtwork(key) {
  const raw = (await fs.readFile(path.join(graphicsDir, `${key}.svg`), 'utf8')).trim();
  const match = raw.match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
  if (!match) throw new Error(`Invalid SVG: src/assets/graphics/${key}.svg`);
  return { attrs: match[1], inner: match[2] };
}

// <svg data-artwork="cloud" class="…"></svg> → the same element with the file's attributes and contents.
async function inlineArtwork(html) {
  const placeholders = [...html.matchAll(/<svg data-artwork="([^"]+)"([^>]*)><\/svg>/g)];
  const assets = new Map();
  for (const [, key] of placeholders) if (!assets.has(key)) assets.set(key, await readArtwork(key));
  const result = html.replace(/<svg data-artwork="([^"]+)"([^>]*)><\/svg>/g, (_, key, attrs) => {
    const asset = assets.get(key);
    return `<svg data-artwork="${key}"${attrs}${asset.attrs}>${asset.inner}</svg>`;
  });
  return { html: result, count: placeholders.length };
}

async function programArtworkModule() {
  const programArt = {};
  for (const key of programKeys) {
    const asset = await readArtwork(`vignettes/${key}`);
    programArt[key] = `<svg data-artwork="vignettes/${key}" class="artwork-inline" focusable="false" aria-hidden="true"${asset.attrs}>${asset.inner}</svg>`;
  }
  return '// Generated by scripts/build.mjs from src/assets/graphics/vignettes. Do not edit.\nexport const programArt = ' + JSON.stringify(programArt, null, 2) + ';\n';
}

export async function build({ outDir = path.join(root, 'dist'), withServer = false } = {}) {
  await fs.rm(outDir, { recursive: true, force: true });
  await fs.mkdir(outDir, { recursive: true });
  await fs.cp(path.join(srcDir, 'assets'), path.join(outDir, 'assets'), { recursive: true });

  const files = {
    'data.js': await fs.readFile(path.join(srcDir, 'data.js'), 'utf8'),
    'artwork.js': await programArtworkModule(),
    'lead.js': await fs.readFile(path.join(srcDir, 'lead.js'), 'utf8'),
    'app.js': await fs.readFile(path.join(srcDir, 'app.js'), 'utf8'),
    'styles.css': await fs.readFile(path.join(srcDir, 'styles.css'), 'utf8'),
  };
  // Dependencies first, so a module's hash covers the versions of what it imports.
  const versions = {};
  for (const name of ['data.js', 'artwork.js', 'lead.js', 'app.js', 'styles.css']) {
    files[name] = files[name].replace(/from '\.\/([\w-]+\.js)'/g, (_, dependency) => {
      if (!versions[dependency]) throw new Error(`${name} imports ${dependency}, which is not built before it`);
      return `from './${dependency}?v=${versions[dependency]}'`;
    });
    versions[name] = hash(files[name]);
    await fs.writeFile(path.join(outDir, name), files[name]);
  }

  let { html, count } = await inlineArtwork(await fs.readFile(path.join(srcDir, 'index.html'), 'utf8'));
  html = html
    .replace('href="styles.css"', `href="styles.css?v=${versions['styles.css']}"`)
    .replace('src="app.js"', `src="app.js?v=${versions['app.js']}"`);
  if (withServer) {
    if (!html.includes('data-endpoint=""')) throw new Error('src/index.html: the consultation form needs data-endpoint=""');
    html = html.replace('data-endpoint=""', 'data-endpoint="/api/leads"');
  }
  if (!html.includes(`styles.css?v=${versions['styles.css']}`) || !html.includes(`app.js?v=${versions['app.js']}`)) {
    throw new Error('src/index.html must reference styles.css and app.js');
  }
  await fs.writeFile(path.join(outDir, 'index.html'), html);
  return { outDir, artwork: count };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const withServer = process.argv.includes('--with-server');
  const { outDir, artwork } = await build({ withServer });
  console.log(`Built ${path.relative(root, outDir)}/ with ${artwork} inline illustrations${withServer ? ', form posts to /api/leads' : ', static form'}.`);
}
